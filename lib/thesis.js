// 分析プロンプトに差し込むブロックを組み立てる。
export function buildStanceBlock({ stance, thesis }) {
  const parts = [];
  const s = (stance || "").trim();
  if (s) {
    parts.push(`\n\n【利用者の投資方針（ランクの参考にする。ただし事実を曲げない）】\n${s}
方針に合わない型だと判断した場合は、ランクを歪めるのではなく、
「## 投資妙味ランク」の中で「※この銘柄は方針上の避ける型（◯◯）に該当します」と明記してください。`);
  }
  const t = (thesis || "").trim();
  if (t) {
    parts.push(`\n\n【利用者の仮説（＝検証の対象）】\n${t}${THESIS_RULES}`);
  }
  return { block: parts.join(""), hasThesis: !!t };
}

